// The first PRICES.models source of a provider prefix such as "xai:", as an https link, or null.
function priceSource(prefix) {
  for (const [key, entry] of Object.entries(PRICES.models)) {
    if (key.startsWith(prefix) && entry?.source) return `https://${entry.source}`;
  }
  return null;
}

// Plenum's direct providers: Anthropic, then every API provider except OpenRouter. Each has its key page and docs as the Accounts
// drawer shows them, and its price table link. plenum is the provider id the finder uses to set a model or open Accounts.
export function directProviders() {
  const anthropic = {
    id: 'anthropic',
    name: 'Anthropic (Claude)',
    kind: 'direct',
    keyUrl: null,
    docsUrl: null,
    pricingUrl: 'https://platform.claude.com/docs/en/about-claude/pricing',
    plenum: 'anthropic',
  };
  const others = API_PROVIDERS.filter(p => p.id !== 'openrouter').map(p => ({
    id: p.id,
    name: p.label,
    kind: 'direct',
    keyUrl: p.keyUrl ?? null,
    docsUrl: p.docsUrl ?? null,
    pricingUrl: priceSource(`${p.id}:`),
    plenum: p.id,
  }));
  return [anthropic, ...others];
}
