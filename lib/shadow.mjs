// Turn snapshots (pro-05). Each working folder has one private git repository, kept under the state folder at
//   <state folder>/shadow/<id>      id = the first 8 hex characters of the SHA-256 of the folder's real path (lower-cased on Windows);
//                                   12 hex characters when another folder already holds that id (folder.txt says which folder is which)
// The repository records what the folder holds before a chat turn or a build and again after it, so a rewind can put files back
// whoever wrote them: Claude Code, Codex, Gemini CLI, Muse Code or a shell command. It is used by lib/hooks/10-snapshot.mjs,
// lib/routes/snapshots.mjs and, through review.mjs, the Review pane.
//
// Isolation. Every git call names its own GIT_DIR, GIT_WORK_TREE and GIT_INDEX_FILE and reads an empty global configuration, so the
// project's .git (its config, index, hooks, fsmonitor and filter drivers) is never read or run, and its index is never written. Git
// reads no system configuration. The folder's own .gitignore files still apply. Attributes come from the empty tree (GIT_ATTR_SOURCE),
// so a .gitattributes line-ending or filter rule cannot change the bytes a snapshot keeps. Every call runs under runGit (lib/git-run.mjs),
// with its hook folder and fsmonitor switched off, and calls on one repository run one at a time.
//
// What is kept. Files under SNAP_SKIP folders (lib/delegate.mjs) and ignored files are left out, and so are files over MAX_FILE_BYTES
// (lib/checkpoints.mjs): those are written to the repository's info/exclude and removed from its index. A folder with more than
// SNAP_FILES_MAX files, or more than SNAP_TOTAL_MAX bytes of kept files, is not snapshotted at all; the caller says so.
//
// Secrets. Files whose names mark them as secrets (isSecretFileName, lib/guard.mjs: .env files other than the .example, .sample and
// .template ones, private keys and certificates, key stores, .npmrc, .netrc and the like) are left out whatever the folder's .gitignore
// says, because a snapshot is not encrypted. recordTree takes them out of the listing the same way it takes out blocked links: kept out of
// git add and removed from the index, so a file an earlier snapshot recorded is not carried on. They are not restored either: a rewind
// compares two snapshots, neither of which holds them, and changedBetween, diffText and readBlob also hide them in a tree that an older
// version of Plenum made, so a rewind never writes over or removes a secret file of the project.
//
// Links. Git for Windows follows a junction (and git a symbolic link to a folder), so a link made inside the folder that leads to
// ~/.ssh, to Plenum's own folders or out of the project would be copied into the repository and then handed to models through
// @checkpoint and @diff. recordTree therefore looks at every folder above a listed file and at every listed link before anything is
// staged: a link whose real place is a credential folder, Plenum's source or state folder, a .git folder, outside the folder, or a folder
// above itself is left out of the snapshot (kept out of git add and removed from the index). The place test is shared with lib/file-index.mjs.
//
// Refs. Each snapshot is a commit under refs/plenum/<scope id>/<snapshot id>, with the commit message "<scope id> <label>". prune keeps
// the newest KEEP_REFS refs of a scope; gc then runs in the background, when no run uses the folder, after GC_EVERY deletions or a day.
import { promises as fs } from 'node:fs';
import { createHash, randomBytes } from 'node:crypto';
import path from 'node:path';
import { HOME } from './store.mjs';
import { runGit, DIFF_SAFE, emptyHooksDir } from './git-run.mjs';
import { SNAP_SKIP, SNAP_FILES_MAX } from './delegate.mjs';
import { MAX_FILE_BYTES } from './checkpoints.mjs';
import { forbiddenPlace, inside, realAppRoot } from './file-index.mjs';
import { dropSecretSections, isSecretFileName } from './guard.mjs';

export const SNAP_TOTAL_MAX = 1024 * 1024 * 1024;
export const KEEP_REFS = 100;
export const GC_EVERY = 20;
const GC_INTERVAL_MS = 24 * 60 * 60 * 1000;
const GC_RETRY_MS = 5000;
const SNAP_BUDGET_MS = 15000;
const ADD_TIMEOUT_MS = 60000;
const STAT_BATCH = 64;
const SCOPE_RE = /^[A-Za-z0-9_-]{1,64}$/;
const ID_RE = /^\d{13}-[0-9a-f]{4}$/;
// The empty tree is part of every git repository. Reading attributes from it means no .gitattributes file is read.
const EMPTY_TREE = '4b825dc642cb6eb9a060e54bf8d69288fbee4904';
const CONFIG_FLAGS = ['-c', 'core.autocrlf=false', '-c', 'core.safecrlf=false', '-c', 'gc.auto=0'];
const GENERATED_HEAD = '# generated by Plenum: files over 5 MB are not snapshotted';
const ENGLISH = {
  'git-missing': 'git was not found',
  'too-long': 'the folder path is too long for git (259 characters or more)',
  timeout: 'took longer than 15 seconds',
  files: 'more than 20,000 files',
  size: 'more than 1 GB of files',
};

// The reason text for a skipped snapshot, as the chat and the approval cards say it.
export function skipReason(code) {
  return ENGLISH[code] ?? String(code ?? 'unknown');
}

const same = (a, b) => (process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b);
const oneLine = s => String(s ?? '').replace(/[\x00-\x1f\x7f]+/g, ' ').trim();
const clipText = (s, n) => (s.length > n ? `${s.slice(0, n)}…` : s);

// A repository that is found but cannot be used: a stale or broken one is an error for the caller to report.
class ShadowError extends Error {
  constructor(code, message = '') {
    super(message || ENGLISH[code] || code);
    this.code = code;
  }
}

// Locates the repository of a folder. Returns { dir, real }; the folder need not be a git repository.
export async function locate(root) {
  const real = await fs.realpath(root);
  const key = process.platform === 'win32' ? real.toLowerCase() : real;
  const hex = createHash('sha256').update(key).digest('hex');
  const base = path.join(HOME, 'shadow');
  const short = path.join(base, hex.slice(0, 8));
  const owner = await fs.readFile(path.join(short, 'folder.txt'), 'utf8').then(t => t.trim(), () => null);
  if (owner === null || same(owner, real)) return { dir: short, real };
  return { dir: path.join(base, hex.slice(0, 12)), real };
}

// The shared per-repository queue. Every call on one repository waits for the one before it.
const queues = new Map();
function serial(key, task) {
  const prev = queues.get(key) ?? Promise.resolve();
  const run = prev.then(task);
  queues.set(key, run.catch(() => {}));
  return run;
}

// The git environment of a repository: its own directory, the folder as the work tree, its own index, and an empty global config.
function envFor(dir, real) {
  return {
    GIT_DIR: dir,
    GIT_WORK_TREE: real,
    GIT_INDEX_FILE: path.join(dir, 'index'),
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_CONFIG_GLOBAL: path.join(dir, 'empty.gitconfig'),
    GIT_ATTR_SOURCE: EMPTY_TREE,
    GIT_AUTHOR_NAME: 'Plenum',
    GIT_COMMITTER_NAME: 'Plenum',
    GIT_AUTHOR_EMAIL: 'plenum@localhost',
    GIT_COMMITTER_EMAIL: 'plenum@localhost',
  };
}

// Makes the repository if it is not there yet: the folder marker, an empty global config, the info/exclude file, the bare repository.
async function ensureRepo(dir, real) {
  await fs.mkdir(dir, { recursive: true });
  const marker = path.join(dir, 'folder.txt');
  if ((await fs.readFile(marker, 'utf8').catch(() => null)) === null) await fs.writeFile(marker, real);
  const config = path.join(dir, 'empty.gitconfig');
  if ((await fs.stat(config).catch(() => null)) === null) await fs.writeFile(config, '');
  if ((await fs.stat(path.join(dir, 'HEAD')).catch(() => null)) === null) {
    const r = await runGit(['init', '-q', '--bare', '--template=', dir], { cwd: path.dirname(dir), env: { GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: config }, timeoutMs: 20000 });
    if (r.longPath) throw new ShadowError('too-long');
    if (r.notFound) throw new ShadowError('git-missing');
    if (!r.ok) throw new ShadowError('init', `git could not make the snapshot store: ${oneLine(r.stderr).slice(0, 160)}`);
  }
  await fs.mkdir(path.join(dir, 'info'), { recursive: true });
  const exclude = path.join(dir, 'info', 'exclude');
  const base = [...SNAP_SKIP].map(name => `${name}/`).concat(['.git']).join('\n');
  const current = await fs.readFile(exclude, 'utf8').catch(() => '');
  if (!current.startsWith(base)) await fs.writeFile(exclude, `${base}\n`);
}

// Runs one git command in the repository, with the folder as its working directory and the timeout the caller gives.
function git(dir, real, args, { input, timeoutMs, encoding, maxBuffer } = {}) {
  return runGit([...CONFIG_FLAGS, ...args], { cwd: real, env: envFor(dir, real), input, timeoutMs, encoding, maxBuffer });
}

// The error a failed git call stands for. A missing git, a timeout and a plain failure each keep their own code.
function failure(r, what) {
  if (r.longPath) return new ShadowError('too-long');
  if (r.notFound) return new ShadowError('git-missing');
  if (r.timedOut) return new ShadowError('timeout');
  return new ShadowError('git', `git could not ${what}${r.stderr ? `: ${oneLine(r.stderr).slice(0, 160)}` : ''}`);
}

// The deadline a call has left. A call past it throws a timeout, and a git child is given only the time left.
function budget(deadline) {
  const left = deadline - Date.now();
  if (left <= 0) throw new ShadowError('timeout');
  return left;
}

// The .git-style exclude lines for the files over the size limit, anchored to the folder root and escaped.
function largeExcludes(paths) {
  if (!paths.length) return '';
  const lines = paths.map(rel => `/${rel.replace(/([\\*?[\]!#])/g, '\\$1')}`);
  return `${GENERATED_HEAD}\n${lines.join('\n')}\n`;
}

// The paths in the info/exclude section for the files over the size limit, as written by setLargeExcludes.
async function readLargeExcludes(dir) {
  const text = await fs.readFile(path.join(dir, 'info', 'exclude'), 'utf8').catch(() => '');
  const cut = text.indexOf(GENERATED_HEAD);
  if (cut < 0) return [];
  return text.slice(cut).split('\n').slice(1).filter(line => line.startsWith('/')).map(line => line.slice(1).replace(/\\(.)/g, '$1'));
}

// Makes the info/exclude section for the files over the size limit, rewritten only when it changed.
async function setLargeExcludes(dir, large) {
  const exclude = path.join(dir, 'info', 'exclude');
  const text = await fs.readFile(exclude, 'utf8').catch(() => '');
  const cut = text.indexOf(GENERATED_HEAD);
  const head = cut >= 0 ? text.slice(0, cut) : text;
  const next = `${head}${largeExcludes(large)}`;
  if (next !== text) await fs.writeFile(exclude, next);
}

// Which of the given paths are still files over the size limit. A large file that is excluded is never listed by git again, so
// this is how it stays excluded from one snapshot to the next; one that shrank or was removed is dropped from the section.
async function stillLarge(real, rels) {
  const kept = [];
  for (const rel of rels) {
    const st = await fs.lstat(path.join(real, rel)).catch(() => null);
    if (st?.isFile() && st.size > MAX_FILE_BYTES) kept.push(rel);
  }
  return kept;
}

// The sizes of the files git lists. Links are measured as links; folders and missing files are skipped. links are the listed paths that
// are themselves links (the folder links above a path are found by blockedFolderLinks).
async function sizesOf(real, rels, deadline) {
  let total = 0;
  const large = [];
  const links = [];
  for (let i = 0; i < rels.length; i += STAT_BATCH) {
    budget(deadline);
    const batch = rels.slice(i, i + STAT_BATCH);
    const stats = await Promise.all(batch.map(rel => fs.lstat(path.join(real, rel)).catch(() => null)));
    stats.forEach((st, j) => {
      if (!st || !(st.isFile() || st.isSymbolicLink())) return;
      if (st.isSymbolicLink()) links.push(batch[j]);
      if (st.size > MAX_FILE_BYTES) large.push(batch[j]);
      else total += st.size;
    });
  }
  return { total, large, links };
}

// ---------- links ----------

// True when the link at rel (a path under real, written with '/') must not be snapshotted: where it really is does not exist, lies outside
// the folder, is a credential folder or Plenum's own source or state (forbiddenPlace, the test lib/file-index.mjs uses for the @ list), is
// or lies in a .git folder, or is a folder above the link itself (it would list its own files again and again).
async function leadsAway(real, rel, appReal) {
  const abs = path.join(real, rel);
  let place;
  let parent;
  try {
    place = await fs.realpath(abs);
    parent = await fs.realpath(path.dirname(abs));
  } catch {
    return true;
  }
  if (!inside(real, place) || forbiddenPlace(place, { appReal })) return true;
  if (path.relative(real, place).split(path.sep).some(part => part.toLowerCase() === '.git')) return true;
  return inside(place, parent);
}

// True when rel is one of the blocked paths or lies under one.
function underBlocked(blocked, rel) {
  if (blocked.has(rel)) return true;
  for (let at = rel.indexOf('/'); at >= 0; at = rel.indexOf('/', at + 1)) if (blocked.has(rel.slice(0, at))) return true;
  return false;
}

// The folder links, among the folders above the listed paths, that must not be snapshotted: a Set of their paths, and the Set of the links
// that stay (inside the folder). The folders are looked at shallowest first, once each, and a folder under a blocked link is not looked at
// again. A link that stays inside the folder is kept.
async function blockedFolderLinks(real, rels, deadline, appReal) {
  const levels = [];
  const seen = new Set();
  for (const rel of rels) {
    let depth = 0;
    for (let at = rel.indexOf('/'); at >= 0; at = rel.indexOf('/', at + 1)) {
      const dir = rel.slice(0, at);
      if (!seen.has(dir)) {
        seen.add(dir);
        (levels[depth] ??= []).push(dir);
      }
      depth += 1;
    }
  }
  const blocked = new Set();
  const kept = new Set();
  for (const level of levels) {
    const todo = level.filter(dir => !underBlocked(blocked, dir));
    for (let i = 0; i < todo.length; i += STAT_BATCH) {
      budget(deadline);
      const batch = todo.slice(i, i + STAT_BATCH);
      const stats = await Promise.all(batch.map(dir => fs.lstat(path.join(real, dir)).catch(() => null)));
      const linked = batch.filter((dir, j) => stats[j]?.isSymbolicLink());
      const away = await Promise.all(linked.map(dir => leadsAway(real, dir, appReal)));
      linked.forEach((dir, j) => {
        if (away[j]) blocked.add(dir);
        else kept.add(dir);
      });
    }
  }
  return { blocked, kept };
}

// The paths in links (listed paths that are links themselves) that must not be snapshotted, as a list.
async function blockedFileLinks(real, links, deadline, appReal) {
  const out = [];
  for (let i = 0; i < links.length; i += STAT_BATCH) {
    budget(deadline);
    const batch = links.slice(i, i + STAT_BATCH);
    const away = await Promise.all(batch.map(rel => leadsAway(real, rel, appReal)));
    batch.forEach((rel, j) => {
      if (away[j]) out.push(rel);
    });
  }
  return out;
}

// Records the folder's current files in the repository's index and writes its tree. Returns { tree } or { skipped }.
// It does not make a commit or a ref; a caller that keeps the result does that.
async function recordTree(dir, real, deadline) {
  await fs.rm(path.join(dir, 'index.lock'), { force: true }).catch(() => {});
  // The large files that are still large are excluded before the listing, so git does not list them and a shrunk one comes back.
  const kept = await stillLarge(real, await readLargeExcludes(dir));
  await setLargeExcludes(dir, kept);
  const listed = await git(dir, real, ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], { timeoutMs: budget(deadline), maxBuffer: 64 * 1024 * 1024 });
  if (!listed.ok) {
    if (listed.tooBig) return { skipped: 'files' };
    throw failure(listed, 'list the folder');
  }
  const everything = listed.stdout.split('\0').filter(Boolean);
  // The links that lead somewhere a snapshot may not read are taken out of the listing before it is counted and measured, and kept out of
  // git add below. (git has already listed what is behind a folder link, so the files under one are dropped here.)
  const appReal = await realAppRoot();
  const { blocked: blockedDirs, kept: keptDirs } = await blockedFolderLinks(real, everything, deadline, appReal);
  // Secret files are listed whether they are new or already in the index, and are dealt with like the blocked links: counted nowhere,
  // kept out of git add and removed from the index below.
  const secrets = everything.filter(isSecretFileName);
  const rels = blockedDirs.size || secrets.length ? everything.filter(rel => !underBlocked(blockedDirs, rel) && !isSecretFileName(rel)) : everything;
  if (rels.length > SNAP_FILES_MAX) return { skipped: 'files' };
  const { total, large, links } = await sizesOf(real, rels, deadline);
  if (total > SNAP_TOTAL_MAX) return { skipped: 'size' };
  const blocked = [...new Set([...blockedDirs, ...await blockedFileLinks(real, links, deadline, appReal), ...secrets])];
  const every = [...new Set([...kept, ...large])];
  await setLargeExcludes(dir, every);
  if (every.length) {
    // Taken out of the index too, so the files already recorded by an earlier snapshot are not carried into this one.
    // -f: a file recorded earlier and changed since would otherwise make git refuse the removal.
    const removed = await git(dir, real, ['rm', '--cached', '-f', '-q', '--ignore-unmatch', '--pathspec-from-file=-', '--pathspec-file-nul'], {
      input: `${every.join('\0')}\0`,
      timeoutMs: budget(deadline),
    });
    if (!removed.ok) throw failure(removed, 'leave out the large files');
  }
  // A folder link that stays (a junction inside the folder) is read through its own path, and git trusts the stat data it kept for the
  // files under it: a file another folder has rewritten in the same second, at the same size, is not read again, so the snapshot would
  // keep the old bytes. The entries under such a link are dropped here, so add -A reads them again (C-8).
  if (keptDirs.size) {
    const unread = await git(dir, real, ['rm', '-r', '--cached', '-f', '-q', '--ignore-unmatch', '--pathspec-from-file=-', '--pathspec-file-nul'], {
      input: `${[...keptDirs].map(rel => `:(literal)${rel}`).join('\0')}\0`,
      timeoutMs: budget(deadline),
    });
    if (!unread.ok) throw failure(unread, 'read the folder links again');
  }
  // The blocked links and the secret files are left out of the staging by pathspec ('.' is the whole folder, each one an exclusion, taken
  // literally), so their files are never read into the repository. They are then taken out of the index too, so a link an earlier
  // snapshot recorded (before it led somewhere else) or a secret file it recorded is not carried into this one, and nothing under one can
  // reach the tree even if git had listed it.
  const added = await git(dir, real, blocked.length ? ['add', '-A', '--pathspec-from-file=-', '--pathspec-file-nul'] : ['add', '-A'], {
    input: blocked.length ? `.\0${blocked.map(rel => `:(exclude,literal)${rel}`).join('\0')}\0` : undefined,
    timeoutMs: Math.min(ADD_TIMEOUT_MS, budget(deadline)),
  });
  if (!added.ok) throw failure(added, 'record the folder');
  if (blocked.length) {
    // -f: without it git refuses to drop an entry whose staged content differs from both the file and HEAD (a secret file recorded
    // by an earlier snapshot and edited since), and the whole snapshot would fail. With --cached only the index entry is dropped.
    const unlinked = await git(dir, real, ['rm', '-r', '--cached', '-f', '-q', '--ignore-unmatch', '--pathspec-from-file=-', '--pathspec-file-nul'], {
      input: `${blocked.map(rel => `:(literal)${rel}`).join('\0')}\0`,
      timeoutMs: budget(deadline),
    });
    if (!unlinked.ok) throw failure(unlinked, 'leave out the links');
  }
  const written = await git(dir, real, ['write-tree'], { timeoutMs: budget(deadline) });
  if (!written.ok) throw failure(written, 'write the tree');
  return { tree: written.stdout.trim() };
}

// Takes the snapshot for a folder without the queue. See snapshot().
async function takeSnapshot(root, scopeId, label, deadline) {
  const { dir, real } = await locate(root);
  await ensureRepo(dir, real);
  const made = await recordTree(dir, real, deadline);
  if (made.skipped) return { skipped: made.skipped };
  const id = `${Date.now()}-${randomBytes(2).toString('hex')}`;
  const note = `${scopeId} ${oneLine(label).slice(0, 120)}`;
  const commit = await git(dir, real, ['commit-tree', made.tree, '-m', note], { timeoutMs: budget(deadline) });
  if (!commit.ok) throw failure(commit, 'record the snapshot');
  const sha = commit.stdout.trim();
  const ref = await git(dir, real, ['update-ref', `refs/plenum/${scopeId}/${id}`, sha], { timeoutMs: budget(deadline) });
  if (!ref.ok) throw failure(ref, 'name the snapshot');
  return { id, tree: made.tree };
}

// Takes a snapshot of the folder: { id, tree } when it is kept, or { skipped: reason } when it is not. The reasons are the codes
// 'git-missing', 'timeout', 'files' (more than 20,000 files) and 'size' (more than 1 GB); skipReason() says them in words.
// A failure that is not one of these throws a ShadowError-shaped Error with the code 'git'; the caller reports it as a skip.
// label is kept with the snapshot (the commit message). budgetMs is the whole time the call may take, queue included: a git child
// past it is killed by runGit, and the call answers { skipped: 'timeout' }.
export async function snapshot(root, scopeId, label, { budgetMs = SNAP_BUDGET_MS } = {}) {
  if (typeof scopeId !== 'string' || !SCOPE_RE.test(scopeId)) throw new ShadowError('scope', 'the chat has no usable id');
  const deadline = Date.now() + budgetMs;
  const real = await fs.realpath(root);
  const { dir } = await locate(real);
  try {
    return await serial(dir, () => takeSnapshot(real, scopeId, label, deadline));
  } catch (err) {
    if (err instanceof ShadowError && (err.code === 'git-missing' || err.code === 'timeout' || err.code === 'too-long')) return { skipped: err.code };
    throw err;
  }
}

// The folder's current files as a tree, kept nowhere: what a comparison needs when no snapshot is to be kept (the rewind card, the
// Show changes view). Returns { tree } or { skipped }, as snapshot() does.
export async function currentTree(root, { budgetMs = SNAP_BUDGET_MS } = {}) {
  const deadline = Date.now() + budgetMs;
  const real = await fs.realpath(root);
  const { dir } = await locate(real);
  try {
    return await serial(dir, async () => {
      await ensureRepo(dir, real);
      return recordTree(dir, real, deadline);
    });
  } catch (err) {
    if (err instanceof ShadowError && (err.code === 'git-missing' || err.code === 'timeout' || err.code === 'too-long')) return { skipped: err.code };
    throw err;
  }
}

// The size in bytes of each file of a stored tree: a Map of path to size.
export async function treeSizes(root, tree) {
  const { dir, real } = await locate(root);
  const r = await serial(dir, async () => {
    await ensureRepo(dir, real);
    return git(dir, real, ['ls-tree', '-r', '-l', '-z', tree], { timeoutMs: 60000, maxBuffer: 64 * 1024 * 1024 });
  });
  if (!r.ok) throw failure(r, 'read the snapshot');
  const sizes = new Map();
  for (const record of r.stdout.split('\0')) {
    const tab = record.indexOf('\t');
    if (tab < 0) continue;
    const size = Number(record.slice(0, tab).trim().split(/\s+/).pop());
    if (Number.isFinite(size)) sizes.set(record.slice(tab + 1), size);
  }
  return sizes;
}

// The files that differ between two trees, each with its diff, for the Show changes view and the rewind card. At most max files
// come back; total counts them all. A diff git cannot hold (over 64 MB) answers with empty diffs rather than failing.
export async function diffFiles(root, a, b, { max = 200 } = {}) {
  const changed = await changedBetween(root, a, b);
  let sections = new Map();
  try {
    sections = splitDiff(await diffText(root, a, b));
  } catch {
    sections = new Map();
  }
  const files = changed.slice(0, max).map(c => ({ path: c.path, status: c.status, diff: sections.get(c.path) ?? '' }));
  return { files, total: changed.length, truncated: changed.length > max };
}

// The snapshot id of a stored ref, from its name, or null.
function idOfRef(ref, scopeId) {
  const prefix = `refs/plenum/${scopeId}/`;
  return ref.startsWith(prefix) && ID_RE.test(ref.slice(prefix.length)) ? ref.slice(prefix.length) : null;
}

// The tree of a stored snapshot id, or null when it is gone.
async function treeOf(dir, real, scopeId, id) {
  if (!ID_RE.test(id)) return null;
  const r = await git(dir, real, ['rev-parse', '--verify', '-q', `refs/plenum/${scopeId}/${id}^{tree}`], { timeoutMs: 10000 });
  return r.ok ? r.stdout.trim() : null;
}

// The changed paths between two trees: [{ status, path }] with status A (added), M (changed) or D (deleted). Paths are sorted.
// A nested git repository (a gitlink, mode 160000) is listed with nested: true; its commits are not files of this folder, so a rewind
// leaves it as it is. Secret files (isSecretFileName) are never listed. Snapshots made now hold none, but a tree an older version made may, and
// neither a rewind nor a comparison may then write over, remove or show a secret file of the project.
export async function changedBetween(root, a, b) {
  const { dir, real } = await locate(root);
  const r = await serial(dir, async () => {
    await ensureRepo(dir, real);
    // --raw, not --name-status: its records carry the file modes, which tell a nested repository from a file.
    return git(dir, real, ['diff-tree', '-r', '-z', '--no-renames', '--raw', a, b], { timeoutMs: 60000, maxBuffer: 64 * 1024 * 1024 });
  });
  if (!r.ok) throw failure(r, 'compare the snapshots');
  const parts = r.stdout.split('\0');
  const out = [];
  // Each change is two NUL-ended parts: ':oldmode newmode oldid newid status', then the path.
  for (let i = 0; i + 1 < parts.length; i += 2) {
    const meta = /^:(\d+) (\d+) \S+ \S+ (\S)/.exec(parts[i] ?? '');
    const p = parts[i + 1];
    if (!meta || !p) continue;
    if (isSecretFileName(p)) continue;
    const entry = { status: meta[3].charAt(0), path: p };
    if (meta[1] === '160000' || meta[2] === '160000') entry.nested = true;
    out.push(entry);
  }
  return out.sort((x, y) => (x.path < y.path ? -1 : x.path > y.path ? 1 : 0));
}

// The diff between two trees, as git writes it, optionally of one path. The diff options fix the output shape (lib/git-run.mjs).
// The part for a secret file is left out (see changedBetween), and a diff asked for one such path is empty.
export async function diffText(root, a, b, rel) {
  if (rel && isSecretFileName(rel)) return '';
  const { dir, real } = await locate(root);
  const r = await serial(dir, async () => {
    await ensureRepo(dir, real);
    return git(dir, real, ['diff', ...DIFF_SAFE, a, b, '--', ...(rel ? [rel] : [])], { timeoutMs: 60000, maxBuffer: 64 * 1024 * 1024 });
  });
  if (!r.ok) throw failure(r, 'compare the snapshots');
  return dropSecretSections(r.stdout);
}

// The bytes of a file in a stored tree, or null when it is not there, is over the size limit (a stale tree can hold a file that
// has since grown past it; such a file is never written back) or is a secret file, which is never read from a snapshot.
export async function readBlob(root, tree, rel) {
  if (isSecretFileName(rel)) return null;
  const { dir, real } = await locate(root);
  return serial(dir, async () => {
    await ensureRepo(dir, real);
    const size = await git(dir, real, ['cat-file', '-s', `${tree}:${rel}`], { timeoutMs: 20000 });
    if (!size.ok || Number(size.stdout.trim()) > MAX_FILE_BYTES) return null;
    const r = await git(dir, real, ['cat-file', 'blob', `${tree}:${rel}`], { encoding: 'buffer', timeoutMs: 20000, maxBuffer: MAX_FILE_BYTES + 1024 });
    return r.ok ? r.stdout : null;
  });
}

// The tree a snapshot id names, for the rewind route. Returns null when the id is not kept.
export async function treeFor(root, scopeId, id) {
  if (typeof scopeId !== 'string' || !SCOPE_RE.test(scopeId)) return null;
  const { dir, real } = await locate(root);
  return serial(dir, async () => {
    await ensureRepo(dir, real);
    return treeOf(dir, real, scopeId, id);
  });
}

// The newest snapshot id of a scope with the given label, or null. The label is the commit message's text after the scope id.
export async function newestWithLabel(root, scopeId, label) {
  if (typeof scopeId !== 'string' || !SCOPE_RE.test(scopeId)) return null;
  const { dir, real } = await locate(root);
  return serial(dir, async () => {
    await ensureRepo(dir, real);
    const r = await git(dir, real, ['for-each-ref', '--format=%(refname)%00%(contents:subject)', `refs/plenum/${scopeId}/`], { timeoutMs: 20000 });
    if (!r.ok) return null;
    const want = `${scopeId} ${label}`;
    const rows = r.stdout.split('\n').filter(Boolean).map(line => line.split('\0'));
    let best = null;
    for (const [ref, subject] of rows) {
      const id = idOfRef(ref, scopeId);
      if (id && subject === want && (best === null || id > best)) best = id;
    }
    return best;
  });
}

// Files the snapshot of the folder now differs from the newest turn's 'before' snapshot, or from the snapshot named by since. It takes a
// snapshot without keeping it, so nothing is written to the refs. Returns { groups: { snapshot: [...] }, truncated } in the file shape
// the Review pane reads (lib/review.mjs snapshotChanges). A folder that cannot be compared answers with no files.
const REVIEW_FILES_MAX = 300;
const REVIEW_DIFF_MAX = 40000;
export async function reviewChanges(root, scopeId, since) {
  const empty = { groups: { snapshot: [] }, truncated: false };
  if (typeof scopeId !== 'string' || !SCOPE_RE.test(scopeId)) return empty;
  const { dir, real } = await locate(root);
  const base = typeof since === 'string' && ID_RE.test(since)
    ? await treeFor(real, scopeId, since)
    : await newestWithLabel(real, scopeId, 'before').then(id => (id ? treeFor(real, scopeId, id) : null));
  if (!base) return empty;
  let now;
  try {
    now = await serial(dir, () => ensureRepo(dir, real).then(() => recordTree(dir, real, Date.now() + SNAP_BUDGET_MS)));
  } catch {
    return empty;
  }
  if (now.skipped || !now.tree) return empty;
  const changed = await changedBetween(real, base, now.tree);
  const diff = await diffText(real, base, now.tree);
  const sections = splitDiff(diff);
  const files = changed.slice(0, REVIEW_FILES_MAX).map(c => {
    const full = sections.get(c.path) ?? '';
    const capped = full.length > REVIEW_DIFF_MAX;
    const text = capped ? full.slice(0, REVIEW_DIFF_MAX) : full;
    const lines = text.split('\n');
    const added = lines.filter(l => l.startsWith('+') && !l.startsWith('+++')).length;
    const removed = lines.filter(l => l.startsWith('-') && !l.startsWith('---')).length;
    return {
      path: c.path,
      status: c.status,
      added,
      removed,
      binary: /^Binary files /m.test(text),
      tooLarge: false,
      diff: text,
      capped,
      diffHash: createHash('sha256').update(text).digest('hex'),
      hunks: [],
    };
  });
  return { groups: { snapshot: files }, truncated: changed.length > REVIEW_FILES_MAX };
}

// Splits a whole-tree diff into one text per path (the path after "b/" in the header line).
function splitDiff(text) {
  const out = new Map();
  const starts = [];
  const lines = text.split('\n');
  lines.forEach((line, i) => {
    if (line.startsWith('diff --git ')) starts.push(i);
  });
  starts.forEach((start, k) => {
    const end = k + 1 < starts.length ? starts[k + 1] : lines.length;
    const block = lines.slice(start, end).join('\n');
    const header = lines[start];
    const m = header.match(/^diff --git a\/(.*) b\/(.*)$/);
    const p = m ? m[2] : null;
    if (p !== null) out.set(p, block);
  });
  return out;
}

// Removes old snapshot refs of a scope, keeping the newest KEEP_REFS. Then, once GC_EVERY refs have gone or a day has passed, gc runs in
// the background when busy() is false. dropped(ids), when given, is called with the ids of the snapshots removed (the chat marks the turns
// whose code is no longer kept). Returns the number of refs removed.
export async function prune(root, scopeId, { busy = () => false, dropped } = {}) {
  if (typeof scopeId !== 'string' || !SCOPE_RE.test(scopeId)) return 0;
  const { dir, real } = await locate(root);
  let gone = [];
  const removed = await serial(dir, async () => {
    await ensureRepo(dir, real);
    const r = await git(dir, real, ['for-each-ref', '--format=%(refname)', `refs/plenum/${scopeId}/`], { timeoutMs: 20000 });
    if (!r.ok) return 0;
    const ids = r.stdout.split('\n').filter(Boolean).filter(ref => idOfRef(ref, scopeId) !== null).sort();
    const drop = ids.slice(0, Math.max(0, ids.length - KEEP_REFS));
    if (!drop.length) return 0;
    const del = await git(dir, real, ['update-ref', '--stdin'], { input: drop.map(ref => `delete ${ref}\n`).join(''), timeoutMs: 60000 });
    if (!del.ok) throw failure(del, 'remove old snapshots');
    gone = drop.map(ref => idOfRef(ref, scopeId));
    return drop.length;
  });
  if (gone.length && typeof dropped === 'function') dropped(gone);
  if (removed > 0) {
    const count = (deletedSince.get(dir) ?? 0) + removed;
    deletedSince.set(dir, count);
    const last = await fs.readFile(path.join(dir, 'gc-stamp'), 'utf8').then(Number, () => 0);
    if (count >= GC_EVERY || Date.now() - last >= GC_INTERVAL_MS) scheduleGc(dir, real, busy);
  }
  return removed;
}

const deletedSince = new Map();
const gcWaiting = new Set();
// gc runs when busy() is false, in the background, and only after the calls queued before it on the repository.
function scheduleGc(dir, real, busy) {
  if (gcWaiting.has(dir)) return;
  gcWaiting.add(dir);
  const attempt = () => {
    if (busy()) {
      const timer = setTimeout(attempt, GC_RETRY_MS);
      timer.unref?.();
      return;
    }
    serial(dir, async () => {
      const r = await git(dir, real, ['gc', '--prune=now', '--quiet'], { timeoutMs: 600000 });
      if (r.ok) await fs.writeFile(path.join(dir, 'gc-stamp'), String(Date.now())).catch(() => {});
      deletedSince.set(dir, 0);
    }).catch(() => {}).finally(() => gcWaiting.delete(dir));
  };
  attempt();
}
